#!/usr/bin/env bash
set -Eeuo pipefail

for name in CORE_DB_USERNAME WORKLOAD_DB_USERNAME ML_DB_USERNAME BACKUP_DB_USERNAME; do
  value="${!name:-}"
  [[ "$value" =~ ^[A-Za-z0-9_]{1,32}$ ]] || { echo "Invalid $name" >&2; exit 2; }
done
for name in CORE_DB_PASSWORD WORKLOAD_DB_PASSWORD ML_DB_PASSWORD BACKUP_DB_PASSWORD; do
  value="${!name:-}"
  [[ "$value" =~ ^[A-Za-z0-9._~!@#%^+=-]{10,128}$ ]] || { echo "Invalid $name" >&2; exit 2; }
done

MYSQL_PWD="${MYSQL_ROOT_PASSWORD}" mysql -h "${MYSQL_HOST:-localhost}" -uroot <<SQL
CREATE DATABASE IF NOT EXISTS enterprise_core CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS enterprise_workload CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE DATABASE IF NOT EXISTS enterprise_ml CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

CREATE USER IF NOT EXISTS '${CORE_DB_USERNAME}'@'%' IDENTIFIED BY '${CORE_DB_PASSWORD}';
ALTER USER '${CORE_DB_USERNAME}'@'%' IDENTIFIED BY '${CORE_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON enterprise_core.* TO '${CORE_DB_USERNAME}'@'%';

CREATE USER IF NOT EXISTS '${WORKLOAD_DB_USERNAME}'@'%' IDENTIFIED BY '${WORKLOAD_DB_PASSWORD}';
ALTER USER '${WORKLOAD_DB_USERNAME}'@'%' IDENTIFIED BY '${WORKLOAD_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON enterprise_workload.* TO '${WORKLOAD_DB_USERNAME}'@'%';

CREATE USER IF NOT EXISTS '${ML_DB_USERNAME}'@'%' IDENTIFIED BY '${ML_DB_PASSWORD}';
ALTER USER '${ML_DB_USERNAME}'@'%' IDENTIFIED BY '${ML_DB_PASSWORD}';
GRANT ALL PRIVILEGES ON enterprise_ml.* TO '${ML_DB_USERNAME}'@'%';

CREATE USER IF NOT EXISTS '${BACKUP_DB_USERNAME}'@'%' IDENTIFIED BY '${BACKUP_DB_PASSWORD}';
ALTER USER '${BACKUP_DB_USERNAME}'@'%' IDENTIFIED BY '${BACKUP_DB_PASSWORD}';
GRANT SELECT, SHOW VIEW, TRIGGER, EVENT, LOCK TABLES ON enterprise_core.* TO '${BACKUP_DB_USERNAME}'@'%';
GRANT SELECT, SHOW VIEW, TRIGGER, EVENT, LOCK TABLES ON enterprise_workload.* TO '${BACKUP_DB_USERNAME}'@'%';
GRANT SELECT, SHOW VIEW, TRIGGER, EVENT, LOCK TABLES ON enterprise_ml.* TO '${BACKUP_DB_USERNAME}'@'%';
FLUSH PRIVILEGES;
SQL
